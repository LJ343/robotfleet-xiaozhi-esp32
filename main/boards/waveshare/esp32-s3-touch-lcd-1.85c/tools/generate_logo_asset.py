#!/usr/bin/env python3
"""Reproduce the board-local, transparent 120px LVGL9 ARGB8888 logo.

No network, quantization, recoloring, cropping, or runtime image decoder is used.
The LVGL little-endian native ARGB8888 byte order is B, G, R, A.
"""

from hashlib import sha256
from pathlib import Path
import re

from PIL import Image


BOARD = Path(__file__).resolve().parents[1]
SOURCE = BOARD / "assets" / "robotfleet-logo-source.png"
OUTPUT = BOARD / "robotfleet_logo.cc"
MODEL = BOARD / "robotfleet_ui_model.h"


def main():
    # Share the native dimension with the runtime layout, rather than keeping
    # a second independent size that could leave stale generated pixels.
    match = re.search(r"\bconstexpr int kLogoSize = (\d+);", MODEL.read_text(encoding="utf-8"))
    if match is None:
        raise ValueError("Missing kLogoSize in the board-local UI model")
    size = int(match.group(1))
    if not 0 < size <= 256:
        raise ValueError("Logo size must fit the original 256px image")
    source_bytes = SOURCE.read_bytes()
    with Image.open(SOURCE) as image:
        if image.mode != "RGBA" or image.size != (256, 256):
            raise ValueError("Expected the original 256x256 RGBA logo")
        image = image.resize((size, size), resample=getattr(Image, "Resampling", Image).LANCZOS)
        pixels = image.tobytes("raw", "BGRA")
    lines = [
        "// Generated by tools/generate_logo_asset.py; do not edit by hand.",
        f"// Source SHA256: {sha256(source_bytes).hexdigest()}",
        f"// Pixel SHA256 (native BGRA): {sha256(pixels).hexdigest()}",
        '#include "robotfleet_logo.h"',
        '#include "robotfleet_ui_model.h"',
        "",
        "namespace robotfleet {",
        "namespace {",
        "alignas(4) const uint8_t kLogoPixels[] = {",
    ]
    for offset in range(0, len(pixels), 16):
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in pixels[offset:offset + 16]) + ",")
    lines.extend([
        "};",
        "}  // namespace",
        "",
        "static_assert(sizeof(kLogoPixels) == kLogoSize * kLogoSize * 4);",
        "",
        "const lv_image_dsc_t kRobotFleetLogo = {",
        "    .header =",
        "        {",
        "            .magic = LV_IMAGE_HEADER_MAGIC,",
        "            .cf = LV_COLOR_FORMAT_ARGB8888,",
        "            .flags = 0,",
        "            .w = kLogoSize,",
        "            .h = kLogoSize,",
        "            .stride = kLogoSize * 4,",
        "            .reserved_2 = 0,",
        "        },",
        "    .data_size = sizeof(kLogoPixels),",
        "    .data = kLogoPixels,",
        "    .reserved = nullptr,",
        "    .reserved_2 = nullptr,",
        "};",
        "",
        "}  // namespace robotfleet",
        "",
    ])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
